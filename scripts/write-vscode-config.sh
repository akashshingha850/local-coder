#!/usr/bin/env bash
# Writes the Continue extension config that points VSCode at the local gateway.
# Called by `lc vscode`. Safe to re-run: the previous config is backed up.
set -euo pipefail

LC_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
source "$LC_ROOT/config/local-coder.env"
source "$LC_ROOT/config/profiles.sh"
load_profile "$LC_PROFILE"
FIM_SERVED="${FIM_SERVED:-qwen2.5-coder-1.5b}"

BASE="http://127.0.0.1:${LC_GATEWAY_PORT}/v1"
CONT_DIR="$HOME/.continue"
CFG="$CONT_DIR/config.yaml"
mkdir -p "$CONT_DIR"

if [ -f "$CFG" ]; then
  cp "$CFG" "$CFG.bak.$(date +%Y%m%d%H%M%S)"
  echo "  backed up existing config to $CFG.bak.*"
fi

{
cat <<YAML
name: local-coder
version: 1.0.0
schema: v1

# Generated by 'lc vscode'. Everything below runs on this machine.
# No code, prompt, or file ever leaves it.

models:
  # ── the agent brain: chat, edits, multi-file refactors, tool use ──────────
  - name: local-chat
    provider: openai
    model: local-chat
    apiBase: ${BASE}
    apiKey: ${LC_API_KEY}
    roles: [chat, edit, apply, summarize]
    contextLength: ${CHAT_LEN}
    capabilities:
      - tool_use
    defaultCompletionOptions:
      maxTokens: 8192
      temperature: 0.2
      topP: 0.9
YAML

if [ -n "$FIM_MODEL" ]; then
cat <<YAML

  # ── inline autocomplete: small, fast, fill-in-middle ──────────────────────
  - name: ${FIM_SERVED}
    provider: openai
    model: ${FIM_SERVED}
    apiBase: ${BASE}
    apiKey: ${LC_API_KEY}
    roles: [autocomplete]
    contextLength: ${FIM_LEN}
    # Force the plain /v1/completions endpoint; fill-in-middle is not a chat op.
    useLegacyCompletionsEndpoint: true
    autocompleteOptions:
      # Pinned explicitly rather than left to name-sniffing, so renaming the
      # served model can never silently break completion quality.
      template: "<|fim_prefix|>{{{prefix}}}<|fim_suffix|>{{{suffix}}}<|fim_middle|>"
      debounceDelay: 250
      maxPromptTokens: 2048
      prefixPercentage: 0.6
      onlyMyCode: true
      useCache: true
      useImports: true
      useRecentlyEdited: true
    defaultCompletionOptions:
      maxTokens: 256
      temperature: 0.0
      stop: ["<|fim_prefix|>", "<|fim_suffix|>", "<|fim_middle|>", "<|endoftext|>", "\n\n"]
YAML
fi

if [ -n "$EMBED_MODEL" ]; then
cat <<YAML

  # ── embeddings: powers @codebase retrieval over your repo ─────────────────
  - name: local-embed
    provider: openai
    model: local-embed
    apiBase: ${BASE}
    apiKey: ${LC_API_KEY}
    roles: [embed]
YAML
fi

cat <<'YAML'

context:
  - provider: code
  - provider: diff
  - provider: terminal
  - provider: problems
  - provider: folder
  - provider: codebase
YAML
} > "$CFG"

echo "  wrote $CFG"
echo
echo "  Install the extension (once):"
echo "    code --install-extension Continue.continue"
echo
echo "  Then reload VSCode. Open the Continue sidebar and pick 'local-chat'."
